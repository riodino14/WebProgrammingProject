// Countries whose official weekend is Friday + Saturday.
export const FRI_SAT_WEEKEND = new Set(['BD', 'BH', 'DZ', 'EG', 'IQ', 'LY', 'SD', 'SY', 'YE']);

/** Weekend day numbers (0 = Sunday ... 6 = Saturday) for a country. */
export function defaultWeekend(cc) {
  return FRI_SAT_WEEKEND.has(cc) ? [5, 6] : [0, 6];
}

/** A representative country for each currency (used to look up World Bank exchange rates). */
export function currencyToCountry() {
  const map = { USD: 'US', EUR: 'DE', GBP: 'GB', AUD: 'AU', NZD: 'NZ', XOF: 'SN', XAF: 'CM', XCD: 'AG', XPF: 'NC', CHF: 'CH', DKK: 'DK', NOK: 'NO' };
  for (const [cc, [cur]] of Object.entries(COUNTRY_META)) if (!map[cur]) map[cur] = cc;
  return map;
}

/** Turn a country code like "KR" into a flag emoji. */
export function flag(cc) {
  if (!/^[A-Z]{2}$/.test(cc)) return '';
  return String.fromCodePoint(...[...cc].map((c) => 0x1f1a5 + c.charCodeAt(0)));
}
